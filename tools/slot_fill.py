def jong_none(v):
    s = re.sub(r'\{[^}]*\}', '', v).strip()
    if not s: return True
    o = ord(s[-1]) - 0xAC00
    return 0 <= o < 11172 and o % 28 == 0


def values(k):
    st, (p0C, p0D, p0E, p0F, p10), laugh, tsk, call, yobi, but, so, wow = C[k]
    s01, s02, s04, s05, s07, s08 = STYLE[st]
    v = {'01': s01, '02': s02, '03': but, '04': s04, '05': s05, '06': wow, '07': s07, '08': s08, '09': so, '0A': yobi, '0B': E,
         '0C': p0C, '0D': p0D, '0E': p0E, '0F': p0F, '10': p10, '11': SUBJ.get(p0D, p0D + '가'), '12': SUBJ.get(p0C, p0C + '가'), '13': laugh, '14': tsk, '15': call}
    for c in ('0C', '0D', '0E', '0F', '10', '15'):
        assert jong_none(v[c]), (k, c, v[c])
    return v


def main(write):
    n = 0
    for p in sorted(glob.glob(os.path.join(TSV, 'cc_slot_*.tsv'))):
        raw = open(p, 'rb').read(); bom = raw.startswith(b'\xef\xbb\xbf')
        text = raw.decode('utf-8-sig'); nl = '\r\n' if '\r\n' in text else '\n'
        lines = text.split(nl); out = []
        for ln in lines:
            f = ln.split('\t')
            m = re.match(r'exe:(\d+)-(\d+) ', f[2]) if len(f) >= 6 else None
            if m and not f[5].strip():
                gi, k = int(m.group(1)), int(m.group(2)); code = '%02X' % (gi - 1)
                if 1 <= k <= 48: f[5] = values(k)[code]; n += 1
                elif k >= 49: f[5] = f[4]; n += 1          # 빈 칸·표 끝 표지 = 원문 그대로
            out.append('\t'.join(f))
        if write:
            data = nl.join(out).encode('utf-8'); open(p, 'wb').write((b'\xef\xbb\xbf' if bom else b'') + data)
    print('채운 칸', n, '(쓰기)' if write else '(미리보기)')
    for k in (1, 6, 12, 16, 34):
        print(k, values(k))


